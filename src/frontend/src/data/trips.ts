export function filterByRegion(trips: Trip[], region: string): Trip[] {
  return trips.filter(
    (t) =>
      t.country.toLowerCase() === region.toLowerCase() ||
      t.region.toLowerCase().includes(region.toLowerCase()) ||
      (t.subRegion?.toLowerCase().includes(region.toLowerCase()) ?? false),
  );
}

export function filterByDifficulty(trips: Trip[], difficulty: string): Trip[] {
  return trips.filter((t) =>
    t.difficulty.toLowerCase().includes(difficulty.toLowerCase()),
  );
}

export function filterByDuration(trips: Trip[], range: string): Trip[] {
  const ranges: Record<string, [number, number]> = {
    "1": [0, 7],
    "2": [8, 10],
    "3": [11, 14],
    "4": [15, 20],
    "5": [21, 999],
  };
  const [min, max] = ranges[range] ?? [0, 999];
  return trips.filter((t) => t.duration >= min && t.duration <= max);
}

export function filterBySeason(trips: Trip[], season: string): Trip[] {
  return trips.filter((t) => t.season.includes(season.toLowerCase()));
}
